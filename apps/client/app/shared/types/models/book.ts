/**
 * Возможные жанры книг. Использование литерального типа обеспечивает строгую типизацию.
 */
export type BookGenre = 'Современная проза' | 'Исторический роман' | 'Военная фантастика' | 'Философская сказка'

/**
 * Общие уровни сложности для быстрой оценки.
 */
export type BookGeneralDifficulty = 'Начинающий' | 'Средний' | 'Продвинутый'

/**
 * Модель Book: Краткая информация для карточки в каталоге.
 * Содержит только необходимые данные для отображения на витрине.
 */
export interface Book {
  /** Уникальный ID-слаг для URL (например, "le-petit-prince"). */
  id: string

  /** Название для отображения. */
  title: string

  /** Автор книги. */
  author: string

  /** URL-адрес обложки. */
  coverUrl: string

  /** Жанр для фильтрации. */
  genre: BookGenre

  /** Общий уровень сложности. */
  difficulty: BookGeneralDifficulty

  /** Общее количество уникальных слов в тексте. */
  uniqueWords: number
}

/**
 * Модель главы книги для оглавления.
 */
export interface Chapter {
  /** Уникальный ID главы. */
  id: number
  /** Название главы. */
  title: string
  /** Номер страницы, с которой начинается глава. */
  startPage: number
}

/**
 * Модель BookDetails: Полная информация для страницы с деталями о книге.
 * Расширяет базовую модель Book, добавляя подробные данные.
 */
export interface BookDetails extends Omit<Book, 'difficulty'> {
  /** Оригинальное название книги. */
  originalTitle: string

  /** Краткое описание (аннотация). */
  summary: string

  /** Общий текстовый уровень сложности. */
  difficultyGeneral: BookGeneralDifficulty

  /** Формальный уровень сложности по китайской системе (например, "HSK 2"). */
  difficultyFormal: string

  /** Общее количество страниц в книге. */
  pageCount: number

  /** Массив глав книги. */
  chapters: Chapter[]
}

/**
 * Информация о произношении китайского слова.
 */
export interface Pronunciation {
  /** Пиньинь с диакритическими знаками (тоновыми метками), например, "nǐ hǎo". */
  pinyin: string

  /** Транскрипция на русский язык по системе Палладия, например, "ни хао". */
  palladius: string
}

/**
 * Модель Word: Атомарная интерактивная единица в тексте.
 * Описывает одно слово и его метаданные.
 */
export interface Word {
  /** Уникальный ID слова (например, "word-7-0-1"). */
  id: string

  /** Текст слова (один или несколько иероглифов). */
  text: string

  /**
   * Массив из двух чисел [startIndex, endIndex].
   * startIndex - индекс первого символа слова в строке originalText.
   * endIndex - индекс символа, следующего за последним символом слова.
   */
  indices: [number, number]

  /** Перевод слова на русский язык. */
  translation: string

  /** Информация о произношении. */
  pronunciation: Pronunciation

  /** Часть речи (например, "местоимение", "глагол"). */
  partOfSpeech: string
}

/**
 * Модель Sentence: Одно полное предложение.
 */
export interface Sentence {
  /** Уникальный ID предложения (например, "sent-7-0"). */
  id: string

  /** Полный текст предложения на китайском языке со всеми знаками препинания. */
  originalText: string

  /** Перевод предложения на русский язык. */
  translation: string

  /** URL-адрес аудиофайла для озвучки всего предложения. */
  audioUrl: string

  /** Пояснения к грамматическим конструкциям (может отсутствовать). */
  grammarNotes: string | null

  /** Массив интерактивных слов, входящих в это предложение. */
  words: Word[]
}

/**
 * Модель BookPage: Корневой объект для одной страницы в режиме чтения.
 */
export interface BookPage {
  /** Номер текущей страницы. */
  pageNumber: number

  /** Название текущей главы. */
  chapterTitle: string

  /**
   * Содержимое страницы, разбитое на параграфы.
   * Каждый параграф - это массив предложений.
   */
  content: Sentence[][]
}
